// Regenerate submit-indexnow.sh from sitemap.xml so the two can never drift.
// Run after any sitemap change: node scripts/build-indexnow.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

// Both paths are CWD-relative, so running this anywhere but the repo root would
// fail confusingly or read the wrong sitemap.
if (existsSync('sitemap.xml') === false) {
  console.error('sitemap.xml not found in the current directory.');
  console.error('Run this from the repo root: node scripts/build-indexnow.mjs');
  process.exit(1);
}

const sitemap = readFileSync('sitemap.xml', 'utf8');
const paths = [...sitemap.matchAll(/<loc>https:\/\/purposelabstudio\.com([^<]*)<\/loc>/g)]
  .map((m) => m[1] || '/')
  .sort();

if (paths.length === 0) throw new Error('no URLs parsed from sitemap.xml');

const urlLines = paths.map((p) => `  "https://\${HOST}${p}"`).join('\n');

const script = `#!/bin/bash
# IndexNow submission.
# GENERATED by scripts/build-indexnow.mjs from sitemap.xml — do not edit by hand.
# Regenerate with: node scripts/build-indexnow.mjs
# Participating engines: Bing, Yandex, Naver, Seznam, Yep. Google does NOT use IndexNow.
#
# Usage:
#   bash submit-indexnow.sh                  submit every canonical URL
#   bash submit-indexnow.sh URL [URL ...]    submit only the URLs given
#
# IndexNow is a "this changed" signal, not a heartbeat. Announcing all 44 URLs on
# every commit reads as noise to the receiving engines, so CI passes the changed
# URLs on push and only re-announces the full list on the weekly run.

set -euo pipefail

INDEXNOW_KEY="f1f454b32a9646baba021f7af031df07"
HOST="purposelabstudio.com"
KEY_LOCATION="https://\${HOST}/\${INDEXNOW_KEY}.txt"

ALL_URLS=(
${urlLines}
)

if [ "$#" -gt 0 ]; then
  URLS=("$@")
else
  URLS=("\${ALL_URLS[@]}")
fi

# URLs contain no quotes or backslashes, so simple JSON assembly is safe here.
URL_JSON=$(printf '"%s",' "\${URLS[@]}" | sed 's/,$//')
PAYLOAD="{\\"host\\":\\"\${HOST}\\",\\"key\\":\\"\${INDEXNOW_KEY}\\",\\"keyLocation\\":\\"\${KEY_LOCATION}\\",\\"urlList\\":[\${URL_JSON}]}"

echo "Submitting \${#URLS[@]} URLs to IndexNow..."
curl -sS -X POST "https://api.indexnow.org/IndexNow" \\
  -H "Content-Type: application/json; charset=utf-8" \\
  -d "\${PAYLOAD}" -w '\\nHTTP %{http_code}\\n'
`;

writeFileSync('submit-indexnow.sh', script, { mode: 0o755 });
console.log(`submit-indexnow.sh regenerated with ${paths.length} URLs`);
